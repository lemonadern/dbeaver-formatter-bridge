// Package versioning maintains the committed product version definitions.
package versioning

import (
	"bytes"
	"encoding/json"
	"encoding/xml"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var stable = regexp.MustCompile(`^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$`)

// Validate accepts ordinary release versions, excluding prereleases and aliases.
func Validate(version string) error {
	if !stable.MatchString(version) {
		return fmt.Errorf("version must be X.Y.Z without a prefix, leading zeroes or prerelease suffix")
	}
	if major := strings.SplitN(version, ".", 2)[0]; major != "0" && major != "1" {
		return fmt.Errorf("major versions 2 and above require a Go /vN module-path migration; this release tool currently supports 0.x and 1.x only")
	}
	for _, component := range strings.Split(version, ".") {
		if _, err := strconv.ParseUint(component, 10, 31); err != nil {
			return fmt.Errorf("version components must fit OSGi's nonnegative 32-bit integers")
		}
	}
	return nil
}

type replacement struct {
	start, end int
	value      string
}
type change struct {
	name          string
	before, after []byte
	mode          os.FileMode
	temporary     string
}

func generated(version string) []byte {
	return []byte("// Code generated by release prepare; DO NOT EDIT.\n// Copyright 2026 lemonadern\n// SPDX-License-Identifier: Apache-2.0\n\npackage version\n\nconst Version = " + strconv.Quote(version) + "\n")
}

func readVersion(root string) (string, error) {
	data, err := os.ReadFile(filepath.Join(root, "VERSION"))
	if err != nil {
		return "", err
	}
	version := strings.TrimSpace(string(data))
	if err := Validate(version); err != nil {
		return "", fmt.Errorf("VERSION: %w", err)
	}
	return version, nil
}

// Check validates every version definition without modifying any file.
func Check(root string) (string, error) {
	version, err := readVersion(root)
	if err != nil {
		return "", err
	}
	changes, err := plan(root, version)
	if err != nil {
		return "", err
	}
	for _, c := range changes {
		if !bytes.Equal(c.before, c.after) {
			return "", fmt.Errorf("version definition is out of sync: %s; run release prepare %s", c.name, version)
		}
	}
	return version, nil
}

// Prepare validates all inputs before staging replacements. No file is changed
// on a validation or staging failure. A failed rename rolls earlier writes back.
func Prepare(root, version string) error {
	if err := Validate(version); err != nil {
		return err
	}
	changes, err := plan(root, version)
	if err != nil {
		return err
	}
	staged := []change{}
	defer func() {
		for _, c := range staged {
			if c.temporary != "" {
				_ = os.Remove(c.temporary)
			}
		}
	}()
	for _, c := range changes {
		if bytes.Equal(c.before, c.after) {
			continue
		}
		file, err := os.CreateTemp(filepath.Dir(filepath.Join(root, c.name)), ".release-version-*")
		if err != nil {
			return err
		}
		c.temporary = file.Name()
		staged = append(staged, c)
		if _, err := file.Write(c.after); err != nil {
			file.Close()
			return err
		}
		if err := file.Chmod(c.mode); err != nil {
			file.Close()
			return err
		}
		if err := file.Close(); err != nil {
			return err
		}
	}
	applied := []change{}
	rollback := func(cause error) error {
		for i := len(applied) - 1; i >= 0; i-- {
			c := applied[i]
			current, err := os.ReadFile(filepath.Join(root, c.name))
			if err != nil || !bytes.Equal(current, c.after) {
				cause = fmt.Errorf("%w; rollback skipped for concurrently changed file %s", cause, c.name)
				continue
			}
			if err := os.WriteFile(filepath.Join(root, c.name), c.before, c.mode); err != nil {
				cause = fmt.Errorf("%w; rollback %s: %v", cause, c.name, err)
			}
		}
		return cause
	}
	for _, c := range staged {
		current, err := os.ReadFile(filepath.Join(root, c.name))
		if err != nil {
			return rollback(err)
		}
		if !bytes.Equal(current, c.before) {
			return rollback(fmt.Errorf("file changed while preparing: %s", c.name))
		}
		if err := os.Rename(c.temporary, filepath.Join(root, c.name)); err != nil {
			return rollback(err)
		}
		applied = append(applied, c)
	}
	return nil
}

func plan(root, version string) ([]change, error) {
	if err := Validate(version); err != nil {
		return nil, err
	}
	specs := []struct{ name, kind string }{
		{"VERSION", "version"},
		{"plugin/pom.xml", "pom"},
		{"plugin/bundles/formatter-bridge/pom.xml", "pom"},
		{"plugin/features/formatter-bridge/pom.xml", "pom"},
		{"plugin/repository/pom.xml", "pom"},
		{"plugin/bundles/formatter-bridge/META-INF/MANIFEST.MF", "bundle"},
		{"plugin/features/formatter-bridge/feature.xml", "feature"},
		{"extensions/vscode/package.json", "json"},
		{"extensions/vscode/package-lock.json", "lock"},
		{"cli/internal/version/value.go", "go"},
	}
	changes := make([]change, 0, len(specs))
	for _, spec := range specs {
		name := filepath.Join(root, spec.name)
		info, err := os.Lstat(name)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", spec.name, err)
		}
		if !info.Mode().IsRegular() {
			return nil, fmt.Errorf("version definition must be a regular file: %s", spec.name)
		}
		before, err := os.ReadFile(name)
		if err != nil {
			return nil, err
		}
		var after []byte
		switch spec.kind {
		case "version":
			if err = Validate(strings.TrimSpace(string(before))); err == nil {
				after = lineEnding([]byte(version+"\n"), before)
			}
		case "go":
			// The generated file is deliberately small and contains no user edits.
			match := regexp.MustCompile(`(?m)^const Version = "([^"]+)"\r?$`).FindSubmatch(before)
			if len(match) != 2 {
				err = fmt.Errorf("missing generated Version constant")
			} else if err = Validate(string(match[1])); err == nil {
				after = lineEnding(generated(version), before)
			}
		case "pom":
			after, err = replacePOM(before, version, spec.name == "plugin/pom.xml")
		case "bundle":
			re := regexp.MustCompile(`(?m)^Bundle-Version: ([^\r\n]+)`)
			matches := re.FindAllSubmatchIndex(before, -1)
			if len(matches) != 1 {
				err = fmt.Errorf("expected one Bundle-Version")
			} else {
				m := matches[0]
				if err = Validate(string(before[m[2]:m[3]])); err == nil {
					after = apply(before, []replacement{{m[2], m[3], version}})
				}
			}
		case "feature":
			after, err = replaceFeature(before, version)
		case "json":
			after, err = replaceJSON(before, version, false)
		case "lock":
			after, err = replaceJSON(before, version, true)
		}
		if err != nil {
			return nil, fmt.Errorf("%s: %w", spec.name, err)
		}
		changes = append(changes, change{name: spec.name, before: before, after: after, mode: info.Mode().Perm()})
	}
	return changes, nil
}

func apply(data []byte, replacements []replacement) []byte {
	sort.Slice(replacements, func(i, j int) bool { return replacements[i].start > replacements[j].start })
	result := append([]byte(nil), data...)
	for _, r := range replacements {
		result = append(result[:r.start], append([]byte(r.value), result[r.end:]...)...)
	}
	return result
}

func replacePOM(data []byte, version string, parent bool) ([]byte, error) {
	decoder := xml.NewDecoder(bytes.NewReader(data))
	stack := []string{}
	var spans []replacement
	for {
		start := int(decoder.InputOffset())
		token, err := decoder.Token()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, err
		}
		switch t := token.(type) {
		case xml.StartElement:
			stack = append(stack, t.Name.Local)
		case xml.EndElement:
			stack = stack[:len(stack)-1]
		case xml.CharData:
			wanted := "project/parent/version"
			if parent {
				wanted = "project/version"
			}
			if strings.Join(stack, "/") == wanted {
				raw := string(data[start:int(decoder.InputOffset())])
				trimmed := strings.TrimSpace(raw)
				if trimmed == "" {
					continue
				}
				if err := Validate(trimmed); err != nil {
					return nil, err
				}
				offset := strings.Index(raw, trimmed)
				spans = append(spans, replacement{start + offset, start + offset + len(trimmed), version})
			}
		}
	}
	if len(spans) != 1 {
		return nil, fmt.Errorf("expected exactly one product version")
	}
	return apply(data, spans), nil
}

func replaceFeature(data []byte, version string) ([]byte, error) {
	decoder := xml.NewDecoder(bytes.NewReader(data))
	var spans []replacement
	depth := 0
	for {
		start := int(decoder.InputOffset())
		token, err := decoder.Token()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, err
		}
		switch t := token.(type) {
		case xml.StartElement:
			if depth == 0 && t.Name.Local == "feature" {
				raw := data[start:int(decoder.InputOffset())]
				re := regexp.MustCompile(`\bversion\s*=\s*"([^"]+)"`)
				m := re.FindSubmatchIndex(raw)
				if len(m) != 4 {
					return nil, fmt.Errorf("missing feature version")
				}
				if err := Validate(string(raw[m[2]:m[3]])); err != nil {
					return nil, err
				}
				spans = append(spans, replacement{start + m[2], start + m[3], version})
			}
			depth++
		case xml.EndElement:
			depth--
		}
	}
	if len(spans) != 1 {
		return nil, fmt.Errorf("expected one feature root")
	}
	return apply(data, spans), nil
}

func replaceJSON(data []byte, version string, lock bool) ([]byte, error) {
	if !json.Valid(data) {
		return nil, fmt.Errorf("invalid JSON")
	}
	decoder := json.NewDecoder(bytes.NewReader(data))
	var spans []replacement
	var walk func([]string) error
	walk = func(keys []string) error {
		before := int(decoder.InputOffset())
		token, err := decoder.Token()
		if err != nil {
			return err
		}
		switch t := token.(type) {
		case json.Delim:
			switch t {
			case '{':
				for decoder.More() {
					key, err := decoder.Token()
					if err != nil {
						return err
					}
					name, ok := key.(string)
					if !ok {
						return fmt.Errorf("invalid object key")
					}
					if err := walk(append(append([]string(nil), keys...), name)); err != nil {
						return err
					}
				}
			case '[':
				for decoder.More() {
					if err := walk(append(append([]string(nil), keys...), "[]")); err != nil {
						return err
					}
				}
			default:
				return fmt.Errorf("unexpected JSON delimiter")
			}
			_, err = decoder.Token()
			return err
		default:
			wanted := len(keys) == 1 && keys[0] == "version" || lock && len(keys) == 3 && keys[0] == "packages" && keys[1] == "" && keys[2] == "version"
			if wanted {
				old, ok := token.(string)
				if !ok {
					return fmt.Errorf("version must be a string")
				}
				if err := Validate(old); err != nil {
					return err
				}
				end := int(decoder.InputOffset())
				for before < end && strings.ContainsRune(" \t\r\n,:", rune(data[before])) {
					before++
				}
				if before >= end || data[before] != '"' {
					return fmt.Errorf("cannot locate JSON version")
				}
				spans = append(spans, replacement{before, end, strconv.Quote(version)})
			}
		}
		return nil
	}
	if err := walk(nil); err != nil {
		return nil, err
	}
	count := 1
	if lock {
		count = 2
	}
	if len(spans) != count {
		return nil, fmt.Errorf("expected %d product version fields, found %d", count, len(spans))
	}
	return apply(data, spans), nil
}

func lineEnding(data, before []byte) []byte {
	if bytes.Contains(before, []byte("\r\n")) {
		return bytes.ReplaceAll(data, []byte("\n"), []byte("\r\n"))
	}
	return data
}
